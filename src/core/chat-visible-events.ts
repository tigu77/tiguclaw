/**
 * **어떤 이벤트가 "대화" 인가** — 이 판정의 유일한 정본 (2026-08-01).
 *
 * ★왜 필요한가(근본): 채팅 화면을 처음부터 다시 그리는 상황이 **둘**인데 서로 다른 데이터를
 *  봤다.
 *   - 새로고침 → SSE 재연결 → 서버가 최근 50건을 **재생** → 그려짐
 *   - 세션 탭 이동 → SSE 는 연결된 채 → 재생 없음 → `/chat-history`(DB)로만 그림
 *  같은 일인데 소스가 달라, DB 에 없는 종류는 **탭 이동에서만 사라졌다**(사용자 신고:
 *  "선택지가 갔다 오면 없어지고 새로고침하면 다시 생긴다"). 종류가 늘 때마다 양쪽에 따로
 *  가르쳐야 했고, 안 가르친 것이 조용히 갈렸다.
 *
 *  게다가 재생은 **최근 50건 창**이라, 선택지 이후 이벤트가 50건 넘게 지나가면
 *  **새로고침해도 안 돌아온다**. "새로고침하면 된다" 는 것 자체가 운이었다.
 *
 *  → 복원의 진실 소스를 **DB 하나로** 모은다. 대화에 보여야 하는 이벤트는 `chat_log` 에
 *    남고, `/chat-history` 가 상황과 무관하게 같은 것을 돌려준다.
 *
 * ★판정 기준: **프런트가 채팅 스트림에 버블을 만드는가.** 카드 상태만 바꾸거나(turn_done 의
 *  비용 고정), 다른 뷰로 가는 것(endpoint.call·worker.*·shell.*)은 대화가 아니다.
 *  고volume 스트리밍(llm.delta·llm.activity)도 아니다 — 전자는 본문이 channel.message.out
 *  으로 수렴하고, 후자는 이미 `historyActivities` 가 따로 복원한다.
 *
 * ★목록인데 왜 괜찮은가: 서버는 프런트가 무엇을 버블로 그리는지 알 수 없어 열거가 불가피하다.
 *  대신 **빠지면 요란하게 실패**하게 만든다 — 회귀 검사가 `js/sse.js` 에서 버블 렌더러
 *  호출부를 긁어 이 집합과 대조한다. 조용히 빠지는 목록이 병이지, 목록 자체가 병은 아니다.
 */

/**
 * 채팅 스트림에 버블로 그려지고 **프런트가 복원 빌더를 등록한** 이벤트.
 *
 * ★이 집합과 프런트 레지스트리(`registerChatKindBuilder`)는 **정확히 같아야 한다**.
 *  한쪽만 늘리면 조용히 반쪽이 된다 — 서버만 늘리면 저장은 되는데 안 그려지고(빈 행 적재),
 *  프런트만 늘리면 그릴 것이 DB 에 없다. 회귀가 양방향으로 대조한다.
 *
 * ★아직 안 넣은 후보(버블은 그리지만 복원 빌더가 없다 — 넣으려면 프런트에서
 *  `registerChatKindBuilder` 를 먼저 등록해야 한다):
 *   `scheduler.error` · `scheduler.recovered` · `llm.compacted` · `llm.turn_error` ·
 *   `llm.compaction_stuck` · `self_growth.failure.learned`.
 *  이들은 지금도 SSE 재생에만 의존한다(=탭 이동 시 사라진다). 사용자가 겪은 것은
 *  선택지였고, 나머지는 실측상 드물어(합계 40여 건) 같은 구조로 뒤따라가면 된다.
 */
export const CHAT_VISIBLE_EVENT_TYPES = new Set<string>([
  "prompt.options", // 비서가 선택지를 물었다.
]);

/** 이 이벤트가 대화 기록(chat_log)에 남아야 하는가. */
export const isChatVisibleEvent = (type: string): boolean =>
  CHAT_VISIBLE_EVENT_TYPES.has(type);
