/**
 * 능력 정의 파일의 **이름 판정** — 이 규칙의 유일한 정본 (2026-08-01).
 *
 * ★왜 모았나: `command-tools-mcp` 와 `endpoint-tools-mcp` 에 **같은 정규식이 사본으로**
 *  있었고, 사본 쪽 주석은 *"동일 규칙(module-private 라 복제 1개)"* 이라고 **사본임을
 *  자백**하고 있었다. 같은 날 시크릿 판정에서 똑같은 형상이 **이미 어긋난 채** 발견됐다
 *  (한쪽에만 `CREDENTIAL` 이 있었다) — 자백이 동기화를 보장하지는 않는다.
 *
 * ★타입으로 막힌 중복과는 다르다: `KNOWN_ADAPTERS` 는 `Record<RegionAAdapter, true>` 라
 *  union 이 바뀌면 **컴파일 에러**가 난다(순환 회피를 위한 의도적 사본). 이건 평범한
 *  정규식이라 아무것도 막아주지 않는다 — 그래서 이쪽만 모은다.
 */

/**
 * 사용자 정의 능력(커스텀 명령·엔드포인트)의 이름이 안전한가.
 *
 * 소문자 영숫자로 시작하고 `[a-z0-9_-]` 만 — **디렉터리 탈출 방어**가 목적이다
 * (이름이 곧 파일명이 된다). 대문자·점·슬래시·공백을 막는다.
 */
export const isSafeCapabilityName = (name: string): boolean =>
  name !== "" && /^[a-z0-9][a-z0-9_-]*$/.test(name);
