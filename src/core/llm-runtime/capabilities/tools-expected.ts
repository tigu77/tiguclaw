/**
 * "이 지시는 도구를 **써야** 하는 지시였나" (2026-08-20 — 사용자 신고)
 *
 * 사고: `[agent-no-tools]` 경고가 **도구 0회**만 보고 발화했다. 그런데 사용자가
 * *"다른 작업 하지 말고 정확히 한 줄만 답하세요: SPAWN_OK"* 라고 시킨 핑에서도 떴다 —
 * 에이전트는 시킨 대로 했는데 시스템이 *"결과가 지어낸 것일 수 있습니다"* 라고 말했다.
 *
 * ★전제가 늙었다. 이 경고는 *"서브에이전트는 도구를 쓸 일이 있어서 띄운다"* 를 가정하는데,
 *  배경 스폰(2026-08-19)이 들어오며 **핑·질의·판단**을 시키는 스폰이 정상 용법이 됐다.
 *  기능이 바뀌면 그 기능을 지나는 옛 판정도 다시 봐야 한다.
 *
 * ★그리고 이건 이 레포에 **이미 기록된 부류**다(principle-check Q8): "서브에이전트 도구
 *  이름을 판정 하나로 묶었더니 … 일을 다 한 에이전트를 「안 했다」고 경고했다."
 *  같은 기제가 다른 축에서 재발했다.
 *
 * ★끄지 않는다 — 진짜로 지어내는 경우를 잡는 게 목적이다. 대신 **질문을 좁힌다**:
 *  "도구를 안 썼다" 가 아니라 **"도구가 필요한 지시였는데 안 썼다"**.
 *
 * ★판정을 **어휘 목록으로 하지 않는다**(그런 목록은 늙는다 — 이 레포가 여러 번 겪었다).
 *  대신 **구조**를 본다: 경로 구분자·파일 확장자·셸 명령 꼴·URL. 이것들은 언어가 바뀌어도
 *  같은 모양이고, "파일·명령을 만지라는 지시" 의 정의 그 자체에 가깝다.
 */

/** 사용자가 **도구를 쓰지 말라고 명시**했나 — 그러면 도구 0은 순종이지 태만이 아니다. */
const RESTRICTS_TOOLS =
  /도구[는은를을]?\s*(쓰지|사용하지)\s*(말|마)|다른\s*작업\s*하지\s*말|한\s*줄만|정확히\s*다음|answer\s+only|no\s+tools?\b|without\s+(using\s+)?tools?/i;

/**
 * 지시가 **구조적으로** 파일·명령·네트워크를 요구하나.
 *  - 경로: `/a/b`, `C:\x`, `./x`, `src/foo`
 *  - 확장자: `.ts` `.json` `.md` … (2~5글자 소문자)
 *  - 명령 꼴: `npm …`, `git …`, `python …`, 백틱 안의 명령
 *  - URL
 */
const NEEDS_TOOLS =
  /(^|\s)(\.{0,2}\/[\w.-]+|[A-Za-z]:\\[\w\\.-]+|[\w-]+\/[\w./-]+)|\.[a-z]{2,5}(\s|$|['"`)\]])|(^|\s)(npm|npx|git|python3?|node|cargo|go|make|docker|curl|pytest|tsc)\s+\S|https?:\/\//;

/**
 * 도구 0회를 **경고할 가치가 있나**.
 * `true` = 파일·명령이 필요해 보이는 지시인데 도구를 안 썼다(지어냈을 수 있다).
 */
export const toolsWereExpected = (prompt: string): boolean => {
  const p = typeof prompt === "string" ? prompt : "";
  if (p.trim() === "") return false;
  if (RESTRICTS_TOOLS.test(p)) return false; // 명시적으로 쓰지 말라고 했다.
  return NEEDS_TOOLS.test(p);
};
