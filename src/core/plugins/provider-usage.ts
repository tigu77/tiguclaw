/**
 * 구독 **한도가 얼마나 남았나** — provider 무관 표현 (2026-09-07 정태님).
 *
 * ★재는 축은 **하나뿐**이다: *"주간 한도가 얼마나 남았나 · 시간 한도가 얼마나 남았나."*
 *  «어디서 토큰을 많이 쓰나» 는 **다른 문제**라 여기 안 들어온다(정태님 판정) — 섞으면
 *  화면이 «흥미로운 숫자» 로 붐비고 정작 필요한 답이 안 보인다.
 *
 * ★**「쓴 양」이 아니라 「남은 양」이다.** 사용자가 묻는 것은 «얼마나 남았나» 이고, 그게
 *  행동을 정한다(지금 더 돌릴까 / 기다릴까). provider 는 `used_percent` 로 주지만 그건
 *  저쪽 사정이고, 우리 표현은 사용자의 질문을 따른다.
 *
 * ★★**코어는 이 «모양» 만 안다 — 뜻은 모른다** (2026-09-07 정태님). 처음엔 여기에
 *  `formatUsage`·`windowLabel`·`untilLabel` 을 뒀는데, 그건 코어가 «한도» 라는 도메인을
 *  아는 것이다. 코어가 할 일은 **플러그인 → 라우트 → 화면** 을 잇는 것뿐이다.
 * ★그런데 문장을 **플러그인**이 만들어도 안 된다 — 그러면 영어 화면에 한국어가 샌다
 *  (`i18n-catalogs-and-coverage` 가 정확히 그걸 막는다: *"ko 에선 멀쩡해서 개발
 *  기계에선 안 보인다"*). 그래서 문장은 **카탈로그가 있는 대시보드**가 만든다.
 *  여기 남는 것은 그 셋이 주고받을 **모양** 하나뿐이다.
 *
 * ★**모르면 모른다고 말한다** — 필드를 생략한다. 0 이나 100 으로 뭉개면 그 숫자로 판단하게
 *  된다(이 레포가 도구 지원 삼상태·`fullChars` 에서 쓴 것과 같은 규칙).
 *  실제로 provider 마다 아는 것이 다르다:
 *   - codex : 창별 사용률·리셋 **둘 다** (`chatgpt.com/backend-api/wham/usage`)
 *   - claude: **아직 하나도** — 조회 엔드포인트가 우리에게 200 을 준 적이 없다(성공 0회)
 *
 * ★★**그런데 「모른다」와 「아무 말도 안 한다」는 다르다** (2026-09-07 정태님이 화면을
 *  보내며: *"아무것도 안떠"*). 빈 자리는 두 가지로 읽힌다 — «이 제공자는 원래 한도를 안
 *  알려준다» 와 «지금 못 가져왔다». 그 둘은 사용자가 할 일이 다른데(전자는 포기, 후자는
 *  잠시 뒤 다시), 우리는 그 답을 **로그에만** 두고 있었다. 로그는 우리 것이지 사용자
 *  것이 아니다.
 * ★그래서 «못 쟀다 + 언제 다시 잰다» 를 나를 자리를 하나 둔다(`retryAt`). 이것도 여전히
 *  **모양**이다 — 무슨 문장으로 말할지는 대시보드가 정한다.
 */

/** 한 개의 한도 창. 아는 것만 채운다. */
export interface UsageWindow {
  /** 창 길이(초). 5시간=18000 · 7일=604800. 이걸로 사람이 읽는 이름을 만든다. */
  readonly windowSeconds?: number;
  /** **남은 비율** 0~100. 모르면 생략 — 0 으로 뭉개지 않는다. */
  readonly remainingPercent?: number;
  /** 리셋 시각(epoch ms). 모르면 생략. */
  readonly resetAt?: number;
}

export interface ProviderUsage {
  /** 지금 한도에 걸려 있나. 모르면 생략. */
  readonly limitReached?: boolean;
  /** 창들 — 짧은 것부터. 하나도 모르면 빈 배열이 아니라 `undefined` 를 반환해라. */
  readonly windows: readonly UsageWindow[];
  /** 언제 잰 값인가(epoch ms) — 폴링이라 낡을 수 있다. */
  readonly measuredAt: number;
  /**
   * **못 쟀고, 이 시각 뒤에 다시 잰다**(epoch ms). 창이 비었을 때만 뜻이 있다.
   * ★있으면 화면은 «모름» 이 아니라 «대기 중» 이라고 말한다 — 사용자가 기다릴지 포기할지
   *  정할 수 있게. 없으면 종전대로 아무 말도 안 한다(그 제공자가 원래 안 주는 경우).
   */
  readonly retryAt?: number;
  /**
   * **기다려도 안 된다** — 이 설치/계정에선 못 잰다.
   * ★`retryAt`(잠시 뒤 다시)과 **반대말**이다. 둘을 안 가르면 «19분 뒤 다시 시도» 가
   *  영원히 떠 있게 되고, 그건 모름이 아니라 **거짓 약속**이다(2026-09-07 실측: claude
   *  조회 엔드포인트가 창이 열린 직후 33초에 물어도 꽉 찬 한 시간을 되돌려줬다 — 성공 0회).
   * ★판정은 **증거**로 한다: 서버가 말한 시각까지 기다렸는데 또 거절당한 창이 두 번.
   *  «몇 회 실패» 같은 손으로 고른 숫자가 아니라, «시키는 대로 했는데도 안 됐다» 다.
   */
  readonly unavailable?: boolean;
}
